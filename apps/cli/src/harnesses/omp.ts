import { existsSync, readFileSync, rmSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';
import { writeFileAtomic } from '../atomic-write.js';
import { backupConfigFile } from '../backups.js';
import { defaultExecutable, writeJsonMcp } from './shared.js';
import type { HarnessAdapter, HookPlan } from './types.js';

/*
 * oh-my-pi (`omp`), a fork of the pi coding agent. Tested with omp 18.2.5. Its own documentation and source
 * (github.com/can1357/oh-my-pi, tag v18.2.5) are the reference for every fact used here:
 *
 * - MCP servers: `mcpServers.<name>` in `<agent dir>/mcp.json` (docs/mcp-config.md), the same JSON shape as Claude
 *   Code and Cursor. omp has no `omp mcp add`; servers are added in a session (`/mcp add`) or in that file.
 * - Hooks are TypeScript/JavaScript extensions, not shell commands (docs/extensions.md): a module in
 *   `<agent dir>/extensions/` whose default export receives `pi` and subscribes with `pi.on(event, handler)`.
 * - The agent dir is `PI_CODING_AGENT_DIR` when it is set and not empty (resolved against the working directory),
 *   otherwise `~/<PI_CONFIG_DIR or .omp>/agent` (`DirResolver` and `getConfigDirName` in packages/utils/src/dirs.ts;
 *   both use `||`, so an empty value counts as unset). MCP servers, extensions and skills all hang off it
 *   (`getAgentDir()` in packages/coding-agent/src/discovery/builtin.ts). Named omp profiles (`OMP_PROFILE`,
 *   `~/.omp/profiles/<name>/agent`) are not supported yet.
 * - User-scope skills: `<agent dir>/skills/<name>/SKILL.md` (docs/skills.md).
 */
export function ompAgentDir(): string {
  const override = process.env.PI_CODING_AGENT_DIR;
  if (override) return resolve(override);
  return join(homedir(), process.env.PI_CONFIG_DIR || '.omp', 'agent');
}
export const ompMcpPath = () => join(ompAgentDir(), 'mcp.json');
export const ompExtensionPath = () => join(ompAgentDir(), 'extensions', 'agentdrop.js');

const MARKER = '// Managed by AgentDrop. Do not edit this file; reconnect to regenerate it.';

export const omp = {
  key: 'omp',
  label: 'oh-my-pi (omp)',
  profile: 'omp',
  binaries: ['omp'],
  configRoot: ompAgentDir,
  skillsRoot: () => join(ompAgentDir(), 'skills'),

  registerMcp({ out, options }, { exe, args }) {
    writeJsonMcp(out, 'omp', options.ompConfigPath ?? ompMcpPath(), { type: 'stdio', command: exe, args });
  },

  removeMcp({ out, options }) {
    writeJsonMcp(out, 'omp', options.ompConfigPath ?? ompMcpPath(), null);
  },

  installNotices({ out, options }, { exe, profile }) {
    const path = options.ompExtensionPath ?? ompExtensionPath();
    installOmpExtension(path, exe, profile);
    out.info(`extension: oh-my-pi extension written to ${path}; omp loads it in new sessions`);
    const named = process.env.OMP_PROFILE || process.env.PI_PROFILE;
    if (named && !process.env.PI_CODING_AGENT_DIR)
      out.warn(
        `oh-my-pi profile "${named}" is set in this shell: AgentDrop was connected to omp's default profile only, so omp sessions under "${named}" will not see it`,
      );
  },

  removeNotices({ options }) {
    removeOmpExtension(options.ompExtensionPath ?? ompExtensionPath());
  },

  hookRepair: {
    path: ompExtensionPath,
    plan(path, profiles): HookPlan {
      const installed = installedOmpExtension(path);
      const base = { path, profile: installed?.profile ?? null, command: null, events: [], recorded: [] };
      if (!installed) return { ...base, status: unreadable(path) ? 'unreadable' : 'absent' };
      const { executable, profile } = installed;
      if (!executable || !profile || !profiles.has(profile)) return { ...base, status: 'orphaned' };
      const exe = existsSync(executable) ? executable : resolve(defaultExecutable());
      const current = readFileSync(path, 'utf8') === ompExtensionSource(exe, profile);
      // `command` carries the executable for `apply`; the extension itself holds no shell command
      return { ...base, status: current ? 'current' : 'stale', command: exe, events: [...OMP_EVENTS] };
    },
    apply(path, plan) {
      if (plan.status === 'current' || !plan.command || !plan.profile) return false;
      // a disconnect may have removed it since the plan was made: a repair rewrites, it never brings one back
      return refreshOmpExtension(path, plan.command, plan.profile);
    },
    describe: (plan) => `${plan.events.join(' + ')} in ${plan.path}`,
  },
} as const satisfies HarnessAdapter;

/** An extension file that is there but cannot be read (permissions, a directory): its owner is unknown. */
function unreadable(path: string): boolean {
  try {
    readFileSync(path, 'utf8');
    return false;
  } catch {
    return existsSync(path);
  }
}

/** The omp events the extension subscribes to, as `doctor` reports them. */
const OMP_EVENTS = ['session_start', 'before_agent_start', 'context', 'agent_end'] as const;

export function installOmpExtension(path: string, exe: string, profile: string): void {
  if (existsSync(path) && !readFileSync(path, 'utf8').startsWith(MARKER))
    throw new Error('oh-my-pi extension path already contains an unmanaged file; file was not changed');
  if (existsSync(path)) backupConfigFile(path);
  writeFileAtomic(path, ompExtensionSource(exe, profile), { mode: 0o600 });
}

/** Rewrites the managed extension only while it is still there and still ours; `false` when it is gone. */
export function refreshOmpExtension(path: string, exe: string, profile: string): boolean {
  if (!installedOmpExtension(path)) return false;
  backupConfigFile(path);
  writeFileAtomic(path, ompExtensionSource(exe, profile), { mode: 0o600 });
  return true;
}

export function removeOmpExtension(path: string): boolean {
  if (!existsSync(path) || !readFileSync(path, 'utf8').startsWith(MARKER)) return false;
  backupConfigFile(path);
  rmSync(path);
  return true;
}

/** The executable and profile a managed extension runs, `null` when there is no managed extension. */
export function installedOmpExtension(path: string): { executable: string; profile: string } | null {
  let source: string;
  try {
    source = readFileSync(path, 'utf8');
  } catch {
    return null;
  }
  if (!source.startsWith(MARKER)) return null;
  const constant = (name: string): string => {
    const m = new RegExp(`^const ${name} = ("(?:[^"\\\\]|\\\\.)*");$`, 'm').exec(source);
    try {
      const value: unknown = m?.[1] ? JSON.parse(m[1]) : '';
      return typeof value === 'string' ? value : '';
    } catch {
      return '';
    }
  };
  return { executable: constant('executable'), profile: constant('profile') };
}

/**
 * The managed extension. It maps omp's extension events onto the same `agentdrop pending --in-hook` commands Codex
 * and Claude Code run as hooks, writing the same hook JSON on stdin (omp v18.2.5, packages/coding-agent/src):
 *
 * - `session_start` (omp starts, also with `-c`/`-r`): the person is there, so their notice
 *   (`--hook-output session-start`) is shown with `ctx.ui.notify`. A switch inside a running omp (`/new`, resume,
 *   fork: `session_switch`) is left out on purpose: omp's own "New session started" line replaces a notice shown
 *   then (checked in a live session), and a session-start claim records the items as seen. The next prompt shows
 *   them instead.
 * - `before_agent_start` (a prompt is about to go to the model): the person's notice as above, and the model's view
 *   (`--hook-output prompt-context`) kept for this turn. omp can run this handler again for the same submission
 *   (`#prepareAgentStart` retries when another extension's system prompt override raced a tool change), so an
 *   answer for the same session and prompt within two seconds is reused; a person sending the same words again
 *   later ("continue") gets a fresh list.
 * - `context` (every model call of the turn): the model's view appended as the last message of that call. omp
 *   builds the call from a copy, never saves what this returns, and marks an added message as per-call, so a
 *   provider cache breakpoint stays in front of it (extensions/runner.ts `emitContext`, ai/providers/anthropic.ts).
 *   The system prompt and the history stay byte-identical; see ADR 0024 for why not `systemPrompt` or `message`.
 * - `agent_end` without a continuation: the turn's context is dropped, and the end-of-turn preview
 *   (`--hook-output system-message`) is shown, people only.
 *
 * Subagents of a task run get nothing: omp gives them no UI and, alone among sessions, the `yield` tool their run
 * must end with (`requireYieldTool`, task/executor.ts); a main session in print mode, forked or not, has neither a
 * UI nor that tool. A run without a UI (`omp -p`, json or rpc without a client) is unattended: it shows nothing and
 * tells the CLI so (`AGENTDROP_UNATTENDED=1`), and the model still gets its context. Nothing here throws into omp: a
 * failed, slow (10 s) or malformed answer is no notice.
 */
export function ompExtensionSource(exe: string, profile: string, node: string = process.execPath): string {
  return `${MARKER}
import { spawn } from "node:child_process";

const executable = ${JSON.stringify(exe)};
const profile = ${JSON.stringify(profile)};
// Windows runs no script by its first line: the CLI's .js entry goes through the Node that connected it
const node = ${JSON.stringify(node)};
const launch = process.platform === "win32" && /\\.[cm]?js$/i.test(executable) ? [node, executable] : [executable];
const SESSION_START = ["pending", "--profile", profile, "--in-hook", "--hook-output", "session-start"];
const PROMPT = ["pending", "--profile", profile, "--in-hook", "--hook-output", "prompt-context"];
const STOP = ["pending", "--profile", profile, "--in-hook", "--hook-output", "system-message"];
const BUDGET_MS = 10000;
const REENTRY_MS = 2000;

function run(args, input, attended) {
  return new Promise((done) => {
    const chunks = [];
    let child;
    try {
      child = spawn(launch[0], [...launch.slice(1), ...args], {
        stdio: ["pipe", "pipe", "ignore"],
        // an explicit AGENTDROP_UNATTENDED (scripts, CI) wins, as it does for every other host
        env: { ...process.env, AGENTDROP_UNATTENDED: process.env.AGENTDROP_UNATTENDED || (attended ? "0" : "1") },
      });
    } catch {
      done({});
      return;
    }
    const timer = setTimeout(() => {
      child.kill();
      done({});
    }, BUDGET_MS);
    // decoded once at the end: a character split across two chunks stays whole
    child.stdout.on("data", (chunk) => {
      chunks.push(chunk);
    });
    child.on("error", () => {
      clearTimeout(timer);
      done({});
    });
    child.on("close", () => {
      clearTimeout(timer);
      try {
        const value = JSON.parse(Buffer.concat(chunks).toString("utf8"));
        done(value && typeof value === "object" ? value : {});
      } catch {
        done({});
      }
    });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify(input));
  });
}

const interactive = (ctx) => ctx.mode === undefined || ctx.mode === "tui" || ctx.mode === "rpc";
const attended = (ctx) => Boolean(ctx.hasUI) && interactive(ctx);
function sessionId(ctx) {
  try {
    return ctx.sessionManager.getSessionId() || undefined;
  } catch {
    return undefined;
  }
}
function show(ctx, result) {
  const text = result && result.systemMessage;
  if (!attended(ctx) || typeof text !== "string" || !text.trim()) return;
  try {
    ctx.ui.notify(text, "info");
  } catch {
    // A notice never interrupts an omp session.
  }
}

export default function agentdrop(pi) {
  let isSubagent;
  function subagent(ctx) {
    if (ctx.hasUI) return false;
    if (isSubagent === undefined) {
      try {
        // names (omp 17.0) or tool infos (later)
        isSubagent = pi.getAllTools().some((tool) => (typeof tool === "string" ? tool : tool && tool.name) === "yield");
      } catch {
        return false;
      }
    }
    return isSubagent;
  }
  let last = null;
  let turn = null;
  pi.on("session_start", async (_event, ctx) => {
    if (subagent(ctx) || !attended(ctx)) return;
    show(ctx, await run(SESSION_START, { hook_event_name: "SessionStart", source: "startup", session_id: sessionId(ctx) }, true));
  });
  pi.on("before_agent_start", async (event, ctx) => {
    if (subagent(ctx)) return;
    const session = sessionId(ctx);
    const key = String(session) + "\\n" + String(event && event.prompt);
    let context;
    if (last && last.key === key && Date.now() - last.at < REENTRY_MS) context = last.context;
    else {
      const result = await run(PROMPT, { hook_event_name: "UserPromptSubmit", session_id: session }, attended(ctx));
      show(ctx, result);
      context = result && result.hookSpecificOutput && result.hookSpecificOutput.additionalContext;
      last = { key, at: Date.now(), context };
    }
    turn = typeof context === "string" && context ? { session, context, at: last.at } : null;
  });
  pi.on("context", (event, ctx) => {
    const messages = event && event.messages;
    if (!turn || !Array.isArray(messages) || turn.session !== sessionId(ctx) || subagent(ctx)) return;
    return {
      messages: [...messages, { role: "custom", customType: "agentdrop", content: turn.context, display: false, timestamp: turn.at }],
    };
  });
  pi.on("agent_end", async (event, ctx) => {
    if (event && event.willContinue) return;
    // the submission is over: the same words sent next are a new one, with the list as it is then
    turn = null;
    last = null;
    if (subagent(ctx) || !attended(ctx)) return;
    show(ctx, await run(STOP, { hook_event_name: "Stop", session_id: sessionId(ctx) }, true));
  });
}
`;
}
