function readJson(path: string): Record<string, unknown> {
  if (!existsSync(path)) return {};
  return JSON.parse(readFileSync(path, 'utf8')) as Record<string, unknown>;
}

function backup(path: string): string | null {
  return backupConfigFile(path);
}

/**
 * The one definition of "an AgentDrop pending hook", shared by the writer, the remover, the drift check and
 * `doctor`; if any two disagree, connect appends duplicates or disconnect leaves ours behind. It matches the
 * command name regardless of directory (an npm prefix or nvm switch moves it) and regardless of the script
 * extension pnpm, Volta and Windows shims give it (`agentdrop.mjs`, `agentdrop.js`, `agentdrop.cmd`).
 */
const AGENTDROP_PENDING = /\bagentdrop(?:\.(?:mjs|cjs|js|cmd))?['"]? pending(?:\s|$)/;

export function isAgentDropHookCommand(command: unknown): command is string {
  return typeof command === 'string' && AGENTDROP_PENDING.test(command);
}

/** Preserve unrelated handlers even when they share a group with an AgentDrop handler. */
function withoutPendingHooks(groups: HookGroup[]): HookGroup[] {
  return groups.flatMap((group) => {
    const hooks = group.hooks.filter((hook) => !isAgentDropHookCommand(hook.command));
    return hooks.length === group.hooks.length ? [group] : hooks.length ? [{ ...group, hooks }] : [];
  });
}

/** Splits a POSIX shell command the way `shellQuote` builds one; `null` for anything it cannot read. */
function shellWords(command: string): string[] | null {
  const words: string[] = [];
  let word = '';
  let inWord = false;
  for (let i = 0; i < command.length; i++) {
    const c = command[i] as string;
    if (c === "'") {
      const end = command.indexOf("'", i + 1);
      if (end < 0) return null;
      word += command.slice(i + 1, end);
      i = end;
      inWord = true;
    } else if (c === '"') {
      let j = i + 1;
      for (; j < command.length && command[j] !== '"'; j++) {
        if (command[j] === '\\' && j + 1 < command.length) j++;
        word += command[j];
      }
      if (j >= command.length) return null;
      i = j;
      inWord = true;
    } else if (c === '\\' && i + 1 < command.length) {
      word += command[++i];
      inWord = true;
    } else if (/\s/.test(c)) {
      if (inWord) words.push(word);
      word = '';
      inWord = false;
    } else {
      word += c;
      inWord = true;
    }
  }
  if (inWord) words.push(word);
  return words;
}

/** Recovers what `connect` put into a hook command: the executable it chose and the profile it was run for. */
export function parseHookCommand(command: string): { executable: string; profile: string } | null {
  const words = shellWords(command);
  if (words?.[1] !== 'pending') return null;
  const at = words.indexOf('--profile');
  const executable = words[0];
  const profile = at < 0 ? undefined : words[at + 1];
  return executable && profile ? { executable, profile } : null;
}

export interface InstalledHooks {
  /** Events that currently carry an AgentDrop handler. */
  events: string[];
  /** From the first readable AgentDrop command (Stop first); `null` when none can be parsed. */
  executable: string | null;
  profile: string | null;
}

function ourCommands(doc: Record<string, unknown>, event: string): string[] {
  const hooks = (doc.hooks as Record<string, HookGroup[]> | undefined) ?? {};
  return (Array.isArray(hooks[event]) ? hooks[event] : [])
    .flatMap((group) => (Array.isArray(group?.hooks) ? group.hooks : []))
    .map((hook) => hook?.command)
    .filter(isAgentDropHookCommand);
}

function readJsonQuietly(path: string): Record<string, unknown> | null {
  if (!existsSync(path)) return null;
  try {
    const doc = readJson(path);
    return isRecord(doc) ? doc : null;
  } catch {
    return null;
  }
}

/** `null` when the file has no AgentDrop pending hook (or cannot be read): repair must leave it alone. */
export function installedPendingHooks(path: string): InstalledHooks | null {
  const doc = readJsonQuietly(path);
  if (!doc) return null;
  const events = PENDING_HOOK_EVENTS.filter((event) => ourCommands(doc, event).length > 0);
  if (events.length === 0) return null;
  const parsed =
    PENDING_HOOK_EVENTS.flatMap((event) => ourCommands(doc, event))
      .map(parseHookCommand)
      .find((p) => p !== null) ?? null;
  return { events: [...events], executable: parsed?.executable ?? null, profile: parsed?.profile ?? null };
}

/**
 * What is installed, compared with what this version would write, and which events a repair writes.
 *
 * `absent` means the user never connected this harness, or disconnected it — repair must leave that alone, or
 * an upgrade would silently re-add a hook somebody deliberately removed. `stale` is the case that matters:
 * hooks are written by `connect`, so a release that adds an event (as 0.4.9 added `UserPromptSubmit`) never
 * reaches an existing install on its own.
 *
 * `recorded` is every event AgentDrop has ever written into this file (see hook-record.ts). A missing event is
 * added only when it is not in that set; one that was written and is now gone was removed by a person, and stays
 * removed. Without a record, the events present now stand in for it. An event that is present but differs from
 * what this version writes (command, flags) is always repaired in place.
 */
export function pendingHooksPlan(
  path: string,
  command: string,
  recorded?: readonly string[] | null,
): { status: 'absent' | 'current' | 'stale'; events: string[] } {
  const installed = installedPendingHooks(path);
  const doc = installed ? readJsonQuietly(path) : null;
  if (!installed || !doc) return { status: 'absent', events: [] };
  const known = new Set([...(recorded ?? []), ...installed.events]);
  const events = PENDING_HOOK_EVENTS.filter((event) => installed.events.includes(event) || !known.has(event));
  const stale = events.some((event) => {
    const ours = ourCommands(doc, event);
    const want = expectedCommand(command, event);
    return ours.length === 0 || ours.some((c) => c !== want);
  });
  return { status: stale ? 'stale' : 'current', events: [...events] };
}

export function pendingHooksStatus(
  path: string,
  command: string,
  recorded?: readonly string[] | null,
): 'absent' | 'current' | 'stale' {
  return pendingHooksPlan(path, command, recorded).status;
}

/**
 * Stop previews what arrived at the end of a turn; UserPromptSubmit and SessionStart are the moments a person is
 * certainly at this session, so they show what the person has not seen yet and record it as seen (and give the
 * model its context on each prompt). See docs/HARNESSES.md, "Seen in an agent".
 */
export const PENDING_HOOK_EVENTS = ['Stop', 'UserPromptSubmit', 'SessionStart'] as const;

const HOOK_OUTPUT_FOR_EVENT: Record<string, string> = {
  UserPromptSubmit: 'prompt-context',
  SessionStart: 'session-start',
};

function expectedCommand(command: string, event: string): string {
  const target = HOOK_OUTPUT_FOR_EVENT[event];
  return target ? `${command} --hook-output ${target}` : command;
}

/** Adds our completion notice and next-prompt context without dropping user hooks. */
export function upsertPendingHooks(
  path: string,
  command: string,
  events: readonly string[] = PENDING_HOOK_EVENTS,
): { path: string; backup: string | null } {
  return upsertHooks(path, command, [...events]);
}

export function upsertStopHook(path: string, command: string): { path: string; backup: string | null } {
  return upsertHooks(path, command, ['Stop']);
}

function upsertHooks(
  path: string,
  command: string,
  events: string[],
): { path: string; backup: string | null } {
  const doc = readJson(path);
  const b = backup(path);
  const hooks = ((doc.hooks as Record<string, HookGroup[]> | undefined) ?? {}) as Record<string, HookGroup[]>;
  for (const event of events) {
    hooks[event] = withoutPendingHooks(hooks[event] ?? []);
    hooks[event].push({
      hooks: [
        {
          type: 'command',
          command: expectedCommand(command, event),
          timeout: 10,
        },
      ],
    });
  }
  doc.hooks = hooks;
  writeFileAtomic(path, `${JSON.stringify(doc, null, 2)}\n`);
  return { path, backup: b };
}

export function removeStopHook(path: string): boolean {
  return removeHooks(path, ['Stop']);
}

export function removePendingHooks(path: string): boolean {
  return removeHooks(path, [...PENDING_HOOK_EVENTS]);
}

function removeHooks(path: string, events: string[]): boolean {
  if (!existsSync(path)) return false;
  const doc = readJson(path);
  const hooks = doc.hooks as Record<string, HookGroup[]> | undefined;
  if (!hooks) return false;
  let changed = false;
  for (const event of events) {
    if (!hooks[event]) continue;
    const next = withoutPendingHooks(hooks[event]);
    if (JSON.stringify(next) === JSON.stringify(hooks[event])) continue;
    changed = true;
    if (next.length === 0) delete hooks[event];
    else hooks[event] = next;
  }
  if (!changed) return false;
  backup(path);
  writeFileAtomic(path, `${JSON.stringify(doc, null, 2)}\n`);
  return true;
}

/*
 * Claude Code's status line: one command for the bar at the bottom of every session. AgentDrop fills it only when
 * nothing else does; a person's own status line is never replaced (they can add `agentdrop statusline` to it).
 */
const STATUS_LINE_MARKER = /\bagentdrop(?:\.(?:mjs|cjs|js|cmd))?['"]? statusline(?:\s|$)/;
/** Seconds between refreshes, besides Claude Code's own triggers; the command reads a shared 30 s cache. */
export const STATUS_LINE_REFRESH_S = 30;

export function statusLineCommand(exe: string, profile: string): string {
  return `${shellQuote(exe)} statusline --profile ${shellQuote(profile)}`;
}

export function upsertClaudeStatusLine(
  path: string,
  command: string,
): 'added' | 'updated' | 'current' | 'yours' {
  const doc = existsSync(path) ? readJson(path) : {};
  const current = doc.statusLine as { type?: unknown; command?: unknown } | undefined;
  const ours = typeof current?.command === 'string' && STATUS_LINE_MARKER.test(current.command);
  if (current !== undefined && !ours) return 'yours';
  if (ours && current?.command === command) return 'current';
  if (existsSync(path)) backup(path);
  doc.statusLine = { type: 'command', command, refreshInterval: STATUS_LINE_REFRESH_S };
  writeFileAtomic(path, `${JSON.stringify(doc, null, 2)}\n`);
  return ours ? 'updated' : 'added';
}

export function removeClaudeStatusLine(path: string): boolean {
  if (!existsSync(path)) return false;
  const doc = readJson(path);
  const current = doc.statusLine as { command?: unknown } | undefined;
  if (typeof current?.command !== 'string' || !STATUS_LINE_MARKER.test(current.command)) return false;
  backup(path);
  delete doc.statusLine;
  writeFileAtomic(path, `${JSON.stringify(doc, null, 2)}\n`);
  return true;
}

/** Cursor uses a lowercase `stop` list and `followup_message` rather than Codex/Claude's systemMessage. */
export function upsertCursorStopHook(path: string, command: string): { path: string; backup: string | null } {
  const current = readJson(path);
  if (current.version !== undefined && current.version !== 1)
    throw new Error('Unsupported Cursor hooks.json version; file was not changed');
  if (current.hooks !== undefined && !isRecord(current.hooks))
    throw new Error('Invalid Cursor hooks.json: hooks must be an object; file was not changed');
  const hooks = { ...((current.hooks ?? {}) as Record<string, unknown>) };
  if (hooks.stop !== undefined && !Array.isArray(hooks.stop))
    throw new Error('Invalid Cursor hooks.json: hooks.stop must be an array; file was not changed');
  const stop = ((hooks.stop ?? []) as unknown[]).filter(
    (entry) =>
      !isRecord(entry) || typeof entry.command !== 'string' || !entry.command.includes(CURSOR_HOOK_MARKER),
  );
  stop.push({ command, loop_limit: 1 });
  hooks.stop = stop;
  const backupPath = backup(path);
  writeFileAtomic(path, `${JSON.stringify({ ...current, version: 1, hooks }, null, 2)}\n`, { mode: 0o600 });
  return { path, backup: backupPath };
}

/** Cursor keeps a single `stop` entry, so drift here means the command itself changed. */
export function cursorStopHookStatus(path: string, command: string): 'absent' | 'current' | 'stale' {
  if (!existsSync(path)) return 'absent';
  let doc: Record<string, unknown>;
  try {
    doc = readJson(path);
  } catch {
    return 'absent';
  }
  const hooks = (doc.hooks ?? {}) as Record<string, unknown>;
  const stop = Array.isArray(hooks.stop) ? (hooks.stop as unknown[]) : [];
  const ours = stop.filter(
    (entry) =>
      isRecord(entry) && typeof entry.command === 'string' && entry.command.includes(CURSOR_HOOK_MARKER),
  ) as Array<{ command: string }>;
  if (ours.length === 0) return 'absent';
  return ours.some((entry) => entry.command === command) ? 'current' : 'stale';
}

/** The executable and profile of the installed Cursor stop hook, `null` when there is none to repair. */
export function installedCursorHook(path: string): { executable: string; profile: string } | null {
  const doc = readJsonQuietly(path);
  const hooks = doc && isRecord(doc.hooks) ? doc.hooks : {};
  const stop = Array.isArray(hooks.stop) ? (hooks.stop as unknown[]) : [];
  for (const entry of stop) {
    if (!isRecord(entry) || typeof entry.command !== 'string' || !entry.command.includes(CURSOR_HOOK_MARKER))
      continue;
    const parsed = parseHookCommand(entry.command);
    if (parsed) return parsed;
  }
  return null;
}

export function removeCursorStopHook(path: string): boolean {
  if (!existsSync(path)) return false;
  const current = readJson(path);
  if (!isRecord(current.hooks) || !Array.isArray(current.hooks.stop)) return false;
  const hooks = current.hooks;
  const stop = hooks.stop as unknown[];
  const before = stop.length;
  const next = stop.filter(
    (entry) =>
      !isRecord(entry) || typeof entry.command !== 'string' || !entry.command.includes(CURSOR_HOOK_MARKER),
  );
  if (next.length === before) return false;
  if (next.length === 0) delete hooks.stop;
  else hooks.stop = next;
  backup(path);
  writeFileAtomic(path, `${JSON.stringify(current, null, 2)}\n`, { mode: 0o600 });
  return true;
}

/** OpenCode's completion boundary is the global plugin event `session.idle`. */
export function installOpencodeIdlePlugin(
  path: string,
  exe: string,
  profile: string,
): { path: string; backup: string | null } {
  if (existsSync(path) && !readFileSync(path, 'utf8').startsWith(OPENCODE_PLUGIN_MARKER))
    throw new Error('OpenCode plugin path already contains an unmanaged file; file was not changed');
  const backupPath = existsSync(path) ? backup(path) : null;
  const source = experimentalEnabled()
    ? experimentalOpencodePlugin(exe, profile)
    : `${OPENCODE_PLUGIN_MARKER}
const executable = ${JSON.stringify(exe)};
const profile = ${JSON.stringify(profile)};
let running = false;

export const AgentDropPlugin = async ({ client, $ }) => ({
  event: async ({ event }) => {
    if (event.type !== "session.idle" || running) return;
    running = true;
    try {
      const result = await $\`\${executable} pending --profile \${profile} --in-hook --hook-output opencode\`
        .quiet()
        .nothrow();
      if (result.exitCode !== 0) return;
      const payload = JSON.parse(result.text());
      if (typeof payload.message !== "string" || !payload.message.trim()) return;
      await client.tui.showToast({
        body: {
          title: "AgentDrop",
          message: payload.message.slice(0, 1200),
          variant: "info",
          duration: 10000,
        },
      });
    } catch {
      // Notification checks never interrupt an OpenCode session.
    } finally {
      running = false;
    }
  },
});
`;
  writeFileAtomic(path, source, { mode: 0o600 });
  return { path, backup: backupPath };
}

/** The same plugin plus hidden autorun delivery; only generated when the experimental switch is on. */
function experimentalOpencodePlugin(exe: string, profile: string): string {
  return `${OPENCODE_PLUGIN_MARKER}
const executable = ${JSON.stringify(exe)};
const profile = ${JSON.stringify(profile)};
let running = false;

// Hidden autorun: queue new drops into the most recently active idle session. Off unless \`agentdrop autorun on\`.
let session = null;
let busy = false;
let polling = false;
let autorunTimer = null;

export const AgentDropPlugin = async ({ client, $ }) => {
  const autorun = async () => {
    if (polling) return;
    polling = true;
    let next = null;
    try {
      // Only claim drops when there is an idle session to put them in; otherwise just check the setting.
      const mode = session && !busy ? [] : ["--probe"];
      const result = await $\`\${executable} autorun poll --profile \${profile} \${mode}\`.quiet().nothrow();
      if (result.exitCode !== 0) return;
      const payload = JSON.parse(result.text());
      if (!payload.enabled) return;
      next = Math.max(15, Number(payload.interval_s) || 60) * 1000;
      if (typeof payload.prompt === "string" && payload.prompt && session) {
        await client.session.promptAsync({
          path: { id: session },
          body: { parts: [{ type: "text", text: payload.prompt }] },
        });
      }
    } catch {
      // Autorun never interrupts an OpenCode session.
    } finally {
      polling = false;
      if (autorunTimer) clearTimeout(autorunTimer);
      autorunTimer = next ? setTimeout(autorun, next) : null;
    }
  };
  setTimeout(autorun, 5000);
  return {
    event: async ({ event }) => {
      if (event.type === "session.status") {
        session = event.properties.sessionID;
        busy = event.properties.status.type !== "idle";
      }
      if (event.type !== "session.idle") return;
      session = event.properties.sessionID;
      busy = false;
      if (running) return;
      running = true;
      try {
        const result = await $\`\${executable} pending --profile \${profile} --in-hook --hook-output opencode\`
          .quiet()
          .nothrow();
        if (result.exitCode !== 0) return;
        const payload = JSON.parse(result.text());
        if (typeof payload.message !== "string" || !payload.message.trim()) return;
        await client.tui.showToast({
          body: {
            title: "AgentDrop",
            message: payload.message.slice(0, 1200),
            variant: "info",
            duration: 10000,
          },
        });
      } catch {
        // Notification checks never interrupt an OpenCode session.
      } finally {
        running = false;
      }
    },
  };
};
`;
}

export function removeOpencodeIdlePlugin(path: string): boolean {
  if (!existsSync(path)) return false;
  const source = readFileSync(path, 'utf8');
  if (!source.startsWith(OPENCODE_PLUGIN_MARKER)) return false;
  backup(path);
  rmSync(path);
  return true;
}

/**
 * Codex runs hooks with no flag at all: per the official documentation they are "enabled by default", the opt-out
 * lives at `[features] hooks = false`, and top-level `hooks` is the hook *definition* table (`[[hooks.Stop]]`,
 * plus the `[hooks.state]` trust bookkeeping Codex writes itself).
 *
 * Earlier versions of this CLI appended a bare `hooks = true` at the top level believing it was an enable switch.
 * That makes `hooks` a boolean, which collides with the table Codex expects, and the whole config then fails to
 * parse with `invalid type: boolean \`true\`, expected struct HooksToml in \`hooks\`` — Codex refuses to start a
 * turn at all. This removes that line (and only that line) so an affected machine is repaired on the next run.
 */
export function repairCodexHooksFlag(configPath: string): boolean {
  if (!existsSync(configPath)) return false;
  const current = readFileSync(configPath, 'utf8');
  const lines = current.split('\n');
  const bad = /^[ \t]*(?:hooks|"hooks"|'hooks')[ \t]*=[ \t]*(?:true|false)[ \t]*(?:#.*)?\r?$/;
  let removed = false;
  const kept: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? '';
    if (bad.test(line) || /^\s*\[/.test(line)) {
      // An incomplete prefix means this line is inside a multiline value, not a root assignment/table.
      let complete = false;
      try {
        parseToml(kept.join('\n'));
        complete = true;
      } catch {
        /* Leave multiline strings and other incomplete values untouched. */
      }
      if (complete && /^\s*\[/.test(line)) {
        kept.push(...lines.slice(i));
        break; // All subsequent bare keys belong to a table, including [features].
      }
      if (complete && bad.test(line)) {
        removed = true;
        continue;
      }
    }
    kept.push(line);
  }
  if (!removed) return false;
  const cleaned = kept.join('\n');
  parseToml(cleaned); // Never replace the user's config with an unparseable repair.
  backup(configPath);
  writeFileAtomic(configPath, cleaned);
  return true;
}

function shellQuote(s: string): string {
  return /^[A-Za-z0-9_./:-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}
