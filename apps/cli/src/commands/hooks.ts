/**
 * Stop-event hook: after the agent finishes a turn, `agentdrop pending --in-hook` tells the user (via the
 * client's systemMessage) whether requests, invitations, unread drops or approvals are waiting. Same JSON shape
 * for Codex (`~/.codex/hooks.json`) and Claude Code (`~/.claude/settings.json`).
 */
export const HOOK_MARKER = 'agentdrop pending';
const CURSOR_HOOK_MARKER = '--hook-output cursor';
const OPENCODE_PLUGIN_MARKER = '// Managed by AgentDrop. Do not edit this file; reconnect to regenerate it.';

interface HookEntry {
  type: 'command';
  command: string;
  timeout?: number;
  statusMessage?: string;
}
interface HookGroup {
  matcher?: string;
  hooks: HookEntry[];
}

export function hookCommand(exe: string, profile: string): string {
  return `${shellQuote(exe)} pending --profile ${shellQuote(profile)} --in-hook`;
}

export function cursorHookCommand(exe: string, profile: string): string {
  return `${hookCommand(exe, profile)} --hook-output cursor`;
}

